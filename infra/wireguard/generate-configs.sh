#!/usr/bin/env bash
# =============================================================================
# UASSPAIN — WireGuard Config Generation (all servers)
# =============================================================================
# Generates WireGuard .conf files for each server based on infra/config.sh.
# Each server gets its own config with correct peers, routes, and firewall rules.
#
# Usage: ./infra/wireguard/generate-configs.sh [--server SERVER_NAME]
# =============================================================================
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"
source "$ROOT_DIR/infra/config.sh"

TARGET_SERVER="${1:-all}"
[[ "$1" == "--server" ]] && TARGET_SERVER="${2:-all}"

KEY_DIR="$ROOT_DIR/$WG_KEY_DIR"
CONFIG_DIR="$ROOT_DIR/$WG_CONFIG_DIR"
mkdir -p "$CONFIG_DIR"

step()  { echo -e "\n\033[0;36m==> $1\033[0m"; }
ok()    { echo -e "    \033[0;32mOK: $1\033[0m"; }
fail()  { echo -e "    \033[0;31mERROR: $1\033[0m"; exit 1; }

# ─── Validate keys exist ─────────────────────────────────────────
for s in server1 server2 backup1 backup2 backup3; do
    [[ -f "$KEY_DIR/${s}.privatekey" ]] || fail "Missing key: $KEY_DIR/${s}.privatekey — run generate-keys.sh first"
done

# ─── Helper: build AllowedIPs for a server ───────────────────────
# Returns comma-separated list of VPN IPs this server should route to
get_allowed_ips() {
    local role="$1"
    case "$role" in
        application)
            # App server only needs PostgreSQL
            echo "${SERVER2_VPN_IP}/32"
            ;;
        postgres)
            # PostgreSQL routes to app + all backups
            echo "${SERVER1_VPN_IP}/32, ${BACKUP1_VPN_IP}/32, ${BACKUP2_VPN_IP}/32, ${BACKUP3_VPN_IP}/32"
            ;;
        backup)
            # Backups only need to reach PostgreSQL (for push) and other backups
            echo "${SERVER2_VPN_IP}/32"
            ;;
    esac
}

# ─── Generate config for a single server ─────────────────────────
generate_server_config() {
    local name="$1" role="$2" vpn_ip="$3" vpn_host="$4" peer_public_key="$5" peer_endpoint="$6" psk_file="$7"

    local conf_file="$CONFIG_DIR/${name}.conf"
    local psk_content=""
    if [[ -f "$psk_file" ]]; then
        psk_content="PresharedKey = $(cat "$psk_file")"
    fi

    local allowed_ips
    allowed_ips=$(get_allowed_ips "$role")

    cat > "$conf_file" <<EOF
# =============================================================================
# UASSPAIN — WireGuard Configuration: $name ($role)
# =============================================================================
# Generated by generate-configs.sh — DO NOT EDIT MANUALLY
# Private key: stored in $KEY_DIR/${name}.privatekey (600 permissions)
# =============================================================================

[Interface]
PrivateKey = $(cat "$KEY_DIR/${name}.privatekey")
Address = $vpn_host
ListenPort = $VPN_PORT
# Firewall rules are applied by setup.sh / firewall scripts
# PostUp / PostDown are handled by the firewall scripts

[Peer]
# Remote peer
PublicKey = $peer_public_key
$psk_content
Endpoint = $peer_endpoint
AllowedIPs = $allowed_ips
PersistentKeepalive = 25
EOF

    chmod 600 "$conf_file"
    ok "Config generated: $conf_file"
}

# ─── Server 1 (Application) ─────────────────────────────────────
generate_server_config_for_role() {
    local name="$1"
    case "$name" in
        server1)
            generate_server_config \
                "server1" "application" \
                "$SERVER1_VPN_IP" "$SERVER1_VPN_HOST" \
                "$(cat "$KEY_DIR/server2.publickey")" \
                "${SERVER2_PUBLIC_IP}:${VPN_PORT}" \
                "$KEY_DIR/server1.psk"
            ;;
        server2)
            generate_server_config \
                "server2" "postgres" \
                "$SERVER2_VPN_IP" "$SERVER2_VPN_HOST" \
                "$(cat "$KEY_DIR/server1.publickey")" \
                "${SERVER1_PUBLIC_IP}:${VPN_PORT}" \
                "$KEY_DIR/server2.psk"
            ;;
        backup1)
            generate_server_config \
                "backup1" "backup" \
                "$BACKUP1_VPN_IP" "$BACKUP1_VPN_HOST" \
                "$(cat "$KEY_DIR/server2.publickey")" \
                "${SERVER2_PUBLIC_IP}:${VPN_PORT}" \
                "$KEY_DIR/backup1.psk"
            ;;
        backup2)
            generate_server_config \
                "backup2" "backup" \
                "$BACKUP2_VPN_IP" "$BACKUP2_VPN_HOST" \
                "$(cat "$KEY_DIR/server2.publickey")" \
                "${SERVER2_PUBLIC_IP}:${VPN_PORT}" \
                "$KEY_DIR/backup2.psk"
            ;;
        backup3)
            generate_server_config \
                "backup3" "backup" \
                "$BACKUP3_VPN_IP" "$BACKUP3_VPN_HOST" \
                "$(cat "$KEY_DIR/server2.publickey")" \
                "${SERVER2_PUBLIC_IP}:${VPN_PORT}" \
                "$KEY_DIR/backup3.psk"
            ;;
    esac
}

# ─── Main ────────────────────────────────────────────────────────
step "Generating WireGuard configs..."

if [[ "$TARGET_SERVER" == "all" ]]; then
    for s in server1 server2 backup1 backup2 backup3; do
        generate_server_config_for_role "$s"
    done
else
    generate_server_config_for_role "$TARGET_SERVER"
fi

echo ""
ok "All configs generated in: $CONFIG_DIR"
echo ""
echo "  Topology:"
echo "    Server 1 (App)  ──WG──▶ Server 2 (PostgreSQL)"
echo "    Server 2 (PG)   ──WG──▶ Backup 1"
echo "    Server 2 (PG)   ──WG──▶ Backup 2"
echo "    Server 2 (PG)   ──WG──▶ Backup 3"
echo ""
