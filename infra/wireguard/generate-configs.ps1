# =============================================================================
# UASSPAIN — WireGuard Config Generation (Windows/PowerShell)
# =============================================================================
# Generates WireGuard .conf files for each server.
#
# Usage: .\infra\wireguard\generate-configs.ps1 [-Server SERVER_NAME]
# =============================================================================
param([string]$Server = "all")

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
. "$Root\infra\config.ps1"

function Step($msg)  { Write-Host "`n==> $msg" -ForegroundColor Cyan }
function Ok($msg)    { Write-Host "    OK: $msg" -ForegroundColor Green }
function Fail($msg)  { Write-Host "    ERROR: $msg" -ForegroundColor Red; exit 1 }

$KeyDir = Join-Path $Root $WG_KEY_DIR
$ConfigDir = Join-Path $Root $WG_CONFIG_DIR
if (-not (Test-Path $ConfigDir)) { New-Item -ItemType Directory -Path $ConfigDir -Force | Out-Null }

# ─── Validate keys exist ─────────────────────────────────────────
foreach ($s in @("server1","server2","backup1","backup2","backup3")) {
    if (-not (Test-Path (Join-Path $KeyDir "$s.privatekey"))) {
        Fail "Missing key: $KeyDir\$s.privatekey — run generate-keys.ps1 first"
    }
}

# ─── Server definitions ──────────────────────────────────────────
$ServerDefs = @(
    @{
        Name = "server1"; Role = "application"
        VpnIP = $SERVER1_VPN_IP; VpnHost = $SERVER1_VPN_HOST
        PeerKeyFile = "server2.publickey"; PeerEndpoint = "${SERVER2_PUBLIC_IP}:${VPN_PORT}"
        PSKFile = "server1.psk"
        AllowedIPs = "$SERVER2_VPN_IP/32, $BACKUP1_VPN_IP/32, $BACKUP2_VPN_IP/32, $BACKUP3_VPN_IP/32"
    },
    @{
        Name = "server2"; Role = "postgres"
        VpnIP = $SERVER2_VPN_IP; VpnHost = $SERVER2_VPN_HOST
        PeerKeyFile = "server1.publickey"; PeerEndpoint = "${SERVER1_PUBLIC_IP}:${VPN_PORT}"
        PSKFile = "server2.psk"
        AllowedIPs = "$SERVER1_VPN_IP/32, $BACKUP1_VPN_IP/32, $BACKUP2_VPN_IP/32, $BACKUP3_VPN_IP/32"
    },
    @{
        Name = "backup1"; Role = "backup"
        VpnIP = $BACKUP1_VPN_IP; VpnHost = $BACKUP1_VPN_HOST
        PeerKeyFile = "server2.publickey"; PeerEndpoint = "${SERVER2_PUBLIC_IP}:${VPN_PORT}"
        PSKFile = "backup1.psk"
        AllowedIPs = "$SERVER2_VPN_IP/32"
    },
    @{
        Name = "backup2"; Role = "backup"
        VpnIP = $BACKUP2_VPN_IP; VpnHost = $BACKUP2_VPN_HOST
        PeerKeyFile = "server2.publickey"; PeerEndpoint = "${SERVER2_PUBLIC_IP}:${VPN_PORT}"
        PSKFile = "backup2.psk"
        AllowedIPs = "$SERVER2_VPN_IP/32"
    },
    @{
        Name = "backup3"; Role = "backup"
        VpnIP = $BACKUP3_VPN_IP; VpnHost = $BACKUP3_VPN_HOST
        PeerKeyFile = "server2.publickey"; PeerEndpoint = "${SERVER2_PUBLIC_IP}:${VPN_PORT}"
        PSKFile = "backup3.psk"
        AllowedIPs = "$SERVER2_VPN_IP/32"
    }
)

# ─── Generate configs ────────────────────────────────────────────
Step "Generating WireGuard configs..."

foreach ($def in $ServerDefs) {
    if ($Server -ne "all" -and $def.Name -ne $Server) { continue }

    $privkey = Get-Content (Join-Path $KeyDir "$($def.Name).privatekey") -Raw
    $peerKey = Get-Content (Join-Path $KeyDir $def.PeerKeyFile) -Raw
    $psk = ""
    $pskPath = Join-Path $KeyDir $def.PSKFile
    if (Test-Path $pskPath) {
        $psk = "PresharedKey = " + (Get-Content $pskPath -Raw)
    }

    $conf = @"
# =============================================================================
# UASSPAIN — WireGuard Configuration: $($def.Name) ($($def.Role))
# =============================================================================
# Generated by generate-configs.ps1 — DO NOT EDIT MANUALLY
# =============================================================================

[Interface]
PrivateKey = $privkey
Address = $($def.VpnHost)
ListenPort = $VPN_PORT

[Peer]
PublicKey = $peerKey
$psk
Endpoint = $($def.PeerEndpoint)
AllowedIPs = $($def.AllowedIPs)
PersistentKeepalive = 25
"@

    $confFile = Join-Path $ConfigDir "$($def.Name).conf"
    Set-Content -Path $confFile -Value $conf -Encoding UTF8
    (Get-Item $confFile).Attributes = 'Hidden'
    Ok "Config generated: $confFile"
}

Write-Host ""
Ok "All configs generated in: $ConfigDir"
Write-Host ""
Write-Host "  Topology:"
Write-Host "    Server 1 (App)  --WG--> Server 2 (PostgreSQL)"
Write-Host "    Server 2 (PG)   --WG--> Backup 1"
Write-Host "    Server 2 (PG)   --WG--> Backup 2"
Write-Host "    Server 2 (PG)   --WG--> Backup 3"
Write-Host ""
